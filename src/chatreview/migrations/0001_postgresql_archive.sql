CREATE TABLE sources (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    machine_id uuid NOT NULL REFERENCES machines(id),
    provider text NOT NULL,
    path text NOT NULL,
    source_kind text NOT NULL,
    active_revision_id bigint,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (machine_id, provider, source_kind, path)
);

CREATE TABLE source_revisions (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_id bigint NOT NULL REFERENCES sources(id),
    revision_no integer NOT NULL,
    size_bytes bigint NOT NULL DEFAULT 0,
    mtime_ns bigint NOT NULL DEFAULT 0,
    device bigint,
    inode bigint,
    head_hash text,
    checkpoint_hash text,
    aggregate_hash text,
    ingested_offset bigint NOT NULL DEFAULT 0,
    ingested_lines bigint NOT NULL DEFAULT 0,
    pending_offset bigint,
    pending_length bigint NOT NULL DEFAULT 0,
    pending_hash text,
    parser_version integer NOT NULL DEFAULT 1,
    status text NOT NULL DEFAULT 'pending',
    error_count bigint NOT NULL DEFAULT 0,
    last_error text,
    started_at timestamptz,
    completed_at timestamptz,
    closed_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    updated_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (source_id, revision_no),
    CHECK (status IN ('pending', 'ingesting', 'partial', 'complete', 'failed', 'replaced', 'truncated')),
    CHECK (ingested_offset >= 0 AND ingested_lines >= 0 AND pending_length >= 0)
);


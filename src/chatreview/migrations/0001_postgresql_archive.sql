CREATE OR REPLACE FUNCTION is_actionable_error_signature(value text)
RETURNS integer
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
RETURN CASE
    WHEN value IS NULL THEN 0
    WHEN value ~* '^(fatal|panic|failed|failure|error|exception|traceback|assertionerror|FAILED)(:|\\s|$)' THEN 1
    WHEN value ~* '(command|process).*(exited|failed).*(code|status) [1-9][0-9]*' THEN 1
    ELSE 0
END;

CREATE OR REPLACE FUNCTION is_reportable_error_signature(value text)
RETURNS integer
LANGUAGE sql
IMMUTABLE
PARALLEL SAFE
RETURN is_actionable_error_signature(value);


CREATE TABLE raw_payloads (
    payload_hash text PRIMARY KEY,
    payload bytea NOT NULL,
    byte_length bigint NOT NULL,
    created_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CHECK (payload_hash ~ '^[0-9a-f]{64}$'),
    CHECK (byte_length = octet_length(payload))
);

CREATE TABLE raw_records (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_revision_id bigint NOT NULL REFERENCES source_revisions(id),
    line_no bigint NOT NULL,
    byte_offset bigint NOT NULL,
    byte_length bigint NOT NULL,
    payload_hash text NOT NULL REFERENCES raw_payloads(payload_hash),
    ingested_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    UNIQUE (source_revision_id, line_no),
    UNIQUE (source_revision_id, byte_offset),
    CHECK (line_no > 0 AND byte_offset >= 0 AND byte_length > 0)
);

CREATE INDEX raw_records_payload_idx ON raw_records(payload_hash);

